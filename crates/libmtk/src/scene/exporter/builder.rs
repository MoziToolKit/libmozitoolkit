//! # Scene Mini-Atlas and Model Database Builder
//!
//! Stitches cropped sprites into self-contained Scene Mini-Atlas sheets via `AtlasBuilder`,
//! decodes PBR channels, remaps model UVs, and tree-shakes the model database.

use std::collections::BTreeSet;

use mtk_model::BakedModelDatabase;
use mtk_resource::ResourceLocation;
use mtk_texture::atlas::builder::{AtlasBuilder, AtlasBuilderConfig};
use mtk_texture::atlas::{AtlasAddressMap, AtlasSpriteLocation};
use mtk_texture::DecodedSprite;
use mtk_voxel::SparseVoxelPayload;

use super::cropper::CroppedSprite;
use crate::scene::metadata::SceneMetadata;
use crate::MtkError;

/// Configuration options for building the scene interchange package.
#[derive(Debug, Clone)]
pub struct SceneExporterConfig {
    /// Maximum dimension of the generated scene mini-atlas (default 2048).
    pub max_atlas_size: u32,
    /// Mipmap level alignment (default 0).
    pub mip_level: u32,
}

impl Default for SceneExporterConfig {
    fn default() -> Self {
        Self {
            max_atlas_size: 2048,
            mip_level: 0,
        }
    }
}

/// In-memory artifacts generated by the scene interchange export pipeline.
#[derive(Debug, Clone)]
pub struct SceneExportResult {
    pub metadata: SceneMetadata,
    pub mini_atlas_map: AtlasAddressMap,
    pub mini_atlas_textures: Vec<(String, Vec<u8>)>,
    pub tree_shaken_models: BakedModelDatabase,
    pub sprite_count: usize,
    pub colormaps: Vec<(String, Vec<u8>)>,
    pub biome_resolver_json: Option<String>,
    pub ctm_rules: Vec<mtk_resource::CtmRule>,
    pub warnings: Vec<String>,
}

fn insert_sprite_aliases(map: &mut AtlasAddressMap, key: &str, loc: &AtlasSpriteLocation) {
    for res_loc in mtk_resource::TextureKeyVariants::resource_locations_for_key(key) {
        map.sprites.insert(res_loc, loc.clone());
    }
}

fn insert_anim_aliases(map: &mut AtlasAddressMap, key: &str, loc: &AtlasSpriteLocation) {
    if let Ok(res_loc) = ResourceLocation::parse_texture_path(key) {
        map.anim_sprites.insert(res_loc, loc.clone());
    }
    if let Ok(res_loc) = ResourceLocation::parse(key) {
        map.anim_sprites.insert(res_loc, loc.clone());
    }
}

/// Builds the mini-atlas, remaps model UVs, and tree-shakes the model database.
pub fn build_scene_atlas_and_models(
    crops: Vec<CroppedSprite>,
    source_models: &BakedModelDatabase,
    needed_blockstates: &BTreeSet<String>,
    voxels: &SparseVoxelPayload,
    config: &SceneExporterConfig,
    colormaps: Vec<(String, Vec<u8>)>,
    biome_resolver_json: Option<String>,
    ctm_rules: Vec<mtk_resource::CtmRule>,
) -> Result<SceneExportResult, MtkError> {
    let sprite_count = crops.len();

    let mut mini_atlas_map = AtlasAddressMap::new();
    let mut mini_atlas_textures = Vec::new();
    let mut first_chunk_dims = [0u32, 0u32];

    if !crops.is_empty() {
        let atlas_cfg = AtlasBuilderConfig {
            max_width: config.max_atlas_size,
            max_height: config.max_atlas_size,
            mip_level: config.mip_level,
            padding: 0,
        };
        let atlas_builder = AtlasBuilder::new(atlas_cfg);

        let decoded_sprites: Vec<DecodedSprite> = crops.iter().map(|c| c.sprite.clone()).collect();
        let mut baked_atlas = atlas_builder
            .build_from_sprites_with_category(decoded_sprites, "scene")
            .map_err(MtkError::Texture)?;

        // Decode PBR companions into canonical normal_gl, orm, aux channels
        let _ = mtk_material::pbr::decode_baked_atlas(&mut baked_atlas);

        if let Some(first) = baked_atlas.chunks.first() {
            first_chunk_dims = [first.width, first.height];
        }

        // Authoritative Biome Tint enablement for scene chunks
        for chunk_meta in &mut baked_atlas.address_map.chunks {
            chunk_meta.has_tint = true;
            chunk_meta.refresh_textures();
        }

        // Populate alias mappings for robust string lookups (skin/, banner:, etc.)
        for crop in &crops {
            if let Some(loc) = baked_atlas
                .address_map
                .lookup_static(&crop.sprite.sprite_id)
                .cloned()
            {
                insert_sprite_aliases(&mut baked_atlas.address_map, &crop.key, &loc);
                for alias in &crop.aliases {
                    insert_sprite_aliases(&mut baked_atlas.address_map, alias, &loc);
                }
            }
            if let Some(loc) = baked_atlas
                .address_map
                .lookup_animated(&crop.sprite.sprite_id)
                .cloned()
            {
                insert_anim_aliases(&mut baked_atlas.address_map, &crop.key, &loc);
                for alias in &crop.aliases {
                    insert_anim_aliases(&mut baked_atlas.address_map, alias, &loc);
                }
            }
        }

        // Encode PNG texture layers for all chunks
        for chunk in &baked_atlas.chunks {
            let stem = chunk.file_stem();

            let alb_png = chunk.albedo.to_png_bytes().map_err(MtkError::Texture)?;
            mini_atlas_textures.push((format!("{}.png", stem), alb_png));

            if let Some(norm) = chunk.normal_gl.as_ref().or(chunk.normal.as_ref()) {
                let norm_png = norm.to_png_bytes().map_err(MtkError::Texture)?;
                mini_atlas_textures.push((format!("{}_n.png", stem), norm_png));
            }

            if let Some(orm) = &chunk.orm {
                let orm_png = orm.to_png_bytes().map_err(MtkError::Texture)?;
                mini_atlas_textures.push((format!("{}_orm.png", stem), orm_png));
            }

            if let Some(aux) = &chunk.aux {
                let aux_png = aux.to_png_bytes().map_err(MtkError::Texture)?;
                mini_atlas_textures.push((format!("{}_aux.png", stem), aux_png));
            }

            if let Some(overlay) = &chunk.overlay {
                let over_png = overlay.to_png_bytes().map_err(MtkError::Texture)?;
                mini_atlas_textures.push((format!("{}_overlay.png", stem), over_png));
            }
        }

        mini_atlas_map = baked_atlas.address_map;
    }

    // 2. Tree-shake models & remap UV coordinates to mini-atlas
    let mut tree_shaken_models = BakedModelDatabase::new();

    for state in needed_blockstates {
        if let Some(model) = source_models.get(state) {
            let mut m = model.clone();
            m.remap_to_atlas_with(|tex_key| {
                mini_atlas_map
                    .lookup_str(tex_key)
                    .map(|loc| (loc.frame_0_uv_bounds, loc.chunk_id, loc.texture_id))
            });
            tree_shaken_models.insert(state.clone(), m);
        }

        if let Some(group) = source_models.get_variant_group(state) {
            let mut g = group.clone();
            g.remap_to_atlas_with(|tex_key| {
                mini_atlas_map
                    .lookup_str(tex_key)
                    .map(|loc| (loc.frame_0_uv_bounds, loc.chunk_id, loc.texture_id))
            });
            tree_shaken_models.insert_variant_group(state.clone(), g);
        }
    }

    // 3. Assemble SceneMetadata and Capabilities
    let mut metadata = SceneMetadata::new(voxels.bounds, voxels.len());
    metadata.unique_states_count = voxels.state_palette.len();
    metadata.unique_biomes_count = voxels.biome_palette.len();
    metadata.unique_entities_count = voxels.entity_palette.len();
    metadata.atlas_resolution = first_chunk_dims;
    metadata.has_animated_atlas = !mini_atlas_map.anim_sprites.is_empty();
    metadata.capabilities = crate::scene::metadata::SceneCapabilities {
        has_colormaps: !colormaps.is_empty(),
        has_ctm: !ctm_rules.is_empty(),
        has_pbr: mini_atlas_textures
            .iter()
            .any(|(name, _)| name.ends_with("_orm.png") || name.ends_with("_aux.png")),
        has_dynamic_entities: !voxels.entity_palette.is_empty(),
    };

    Ok(SceneExportResult {
        metadata,
        mini_atlas_map,
        mini_atlas_textures,
        tree_shaken_models,
        sprite_count,
        colormaps,
        biome_resolver_json,
        ctm_rules,
        warnings: Vec::new(),
    })
}
